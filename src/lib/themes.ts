export function getThemeById(id: string): ThemeConfig {
  return AURA_THEMES.find((t) => t.id === id) || AURA_THEMES[0];
}

export function mergeThemeWithCustom(baseThemeId: string, customJson?: string | Partial<ThemeConfig>): ThemeConfig {
  const base = getThemeById(baseThemeId);
  if (!customJson) return base;
  try {
    const parsed = typeof customJson === 'string' ? JSON.parse(customJson) : customJson;
    return {
      ...base,
      ...parsed,
      gradientColors:
        Array.isArray(parsed.gradientColors) && parsed.gradientColors.length === 3
          ? (parsed.gradientColors as [string, string, string])
          : base.gradientColors,
    };
  } catch {
    return base;
  }
}

export function mergeEffectsConfig(effectsJson?: string | Partial<EffectsConfig>): EffectsConfig {
  if (!effectsJson) return DEFAULT_EFFECTS_CONFIG;
  try {
    const parsed = typeof effectsJson === 'string' ? JSON.parse(effectsJson) : effectsJson;
    return {
      ...DEFAULT_EFFECTS_CONFIG,
      ...parsed,
    };
  } catch {
    return DEFAULT_EFFECTS_CONFIG;
  }
}

/**
 * Theme DNA Generator:
 * Creates a harmonious luxury theme configuration from 1-3 user-selected seed colors.
 */
export function generateThemeDNA(
  primaryAccent: string,
  secondaryAccent: string = '#7928CA',
  surfaceBase: string = '#07070C',
  mood: MoodPresetType = 'luxury'
): Partial<ThemeConfig> {
  const moodPreset = MOOD_PRESETS.find((m) => m.id === mood) || MOOD_PRESETS[0];
  return {
    bgColor: surfaceBase,
    gradientColors: [surfaceBase, secondaryAccent, primaryAccent],
    glowColor: primaryAccent,
    accentColor: primaryAccent,
    cardBg: `${surfaceBase}B8`,
    cardBorder: `${primaryAccent}55`,
    textColor: '#F8FAFC',
    secondaryTextColor: '#CBD5E1',
    ...moodPreset.themeOverrides,
  };
}

